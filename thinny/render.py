def to_yaml(value, indent: int = 0) -> str:
    """Minimal YAML for nested dicts, lists and scalars (strings as JSON, which YAML accepts)."""
    pad = "  " * indent
    lines = []
    for key, item in value.items():
        key = json.dumps(key)   # a group's too: unquoted, `on` and `123` are no strings
        if isinstance(item, dict) and item:
            lines.append(f"{pad}{key}:")
            lines.append(to_yaml(item, indent + 1))
        else:
            lines.append(f"{pad}{key}: {json.dumps(item)}")
    return "\n".join(lines)


def merged(base: dict, over: dict) -> dict:
    """`base` with `over` on top, tables merged key by key."""
    result = dict(base)
    for key, value in over.items():
        both = isinstance(value, dict) and isinstance(result.get(key), dict)
        result[key] = merged(result[key], value) if both else value
    return result


def managed_config(s: Settings) -> str:
    config = {}
    if s.model_lock:  # without it, the instance's own config holds these, seeded at instance add
        plugins = ["model-guard", *([s.language_pack] if s.language_pack else []), *(name for name, _ in PLUGINS)]
        config = {
            "model": {"provider": s.model_provider, "default": s.model},
            "agent": {"reasoning_effort": s.reasoning_effort},
            # Pinned lists replace the user's lists, so everything that must be on is listed here.
            "plugins": {"enabled": plugins, "disabled": []},
        }
    config |= {
        # The instance's container is the agent's sandbox.
        "terminal": {"backend": "local"},
        "bot_desktop": {"placement": "terminal"},
        "security": {"redact_secrets": True},
        "approvals": {"mode": s.approvals},
        # Hermes does not borrow Claude Code's or Codex CLI's sign-ins on its own: their refresh tokens rotate, so it
        # could log them out, and with Claude Code the Claude plugin, which runs it.
        "auth": {"adopt_external_logins": False},
        # Else Hermes messages users at every restart of its gateway, e.g. at the nightly update or a reboot.
        "platforms": {platform: {"gateway_restart_notification": False} for platform in ("email", "phone", "telegram")},
    }
    config = merged(s.hermes, config)   # the instance's group's settings, under thinny's own
    return f"# {HEADER}\n# Hermes managed scope: these values win over every instance's own config.\n{to_yaml(config)}\n"


