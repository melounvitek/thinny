def ui_preferences(s: Settings) -> dict[str, str]:
    """Webapp look for a new instance (keys of Hermes's ui-preferences.json)."""
    def key(model):
        return f"{s.model_provider}::{model}"
    prefs = {
        "hermes-desktop-mode-v1": s.theme,
        "hermes.desktop.chat-text-scale.v1": str(s.text_scale),
        "hermes.desktop.interfaceMode.v1": s.interface,
        "hermes.desktop.panesFlipped": "false",
        "hermes.desktop.showAllProfiles": "false",
        "hermes.desktop.model-presets": json.dumps(
            {key(s.model): {"effort": s.reasoning_effort, "serviceTier": "normal", "fast": False}}),
    }
    if s.model_lock:  # the model picker shows the allowed models only
        allowed = [key(m) for m in s.allowed_models]
        prefs["hermes.desktop.visible-models"] = json.dumps(allowed)
        # Models missing here show up as "new" in the model picker.
        prefs["hermes.desktop.known-models"] = json.dumps(sorted(set(allowed) | {key(m) for m in s.known_models}))
    return prefs


def host_for_url(address: str) -> str:
    return f"[{address}]" if ipaddress.ip_address(address).version == 6 else address


def instance_url(s: Settings, name: str, access: str, port: int, *, url: str = "", tailscale_name: str = "") -> str:
    """The address users open; Hermes's webapp.public_url."""
    if access == "lan":
        return f"https://{host_for_url(s.lan_address)}:{port}/"
    if access == "tailscale":
        return f"https://{tailscale_name}:{port}/"
    if access == "local":
        return f"http://{name}.localhost:{port}/"
    return url


def caddyfile(s: Settings, lan_ports: list[int]) -> str:
    sites = "".join(
        f"\nhttps://{host_for_url(s.lan_address)}:{port} {{\n\tbind {s.lan_address}\n\ttls internal\n"
        f"\treverse_proxy 127.0.0.1:{port}\n}}\n"
        for port in lan_ports)
    # No admin API: on localhost it would let any account rewrite the proxy.
    return f"# {HEADER}\n{{\n\tadmin off\n\tskip_install_trust\n}}\n{sites}"


def firewall(interface: str, blocked_networks: list[str]) -> str:
    """nft table for the instance containers (routed NICs named thinny-<port>, addresses in SUBNET).

    A container reaches the internet through `interface` only: no other container, no service of
    the host, no private, tailnet or blocked network, no IPv6. Nothing opens a connection into a
    container. Incus itself drops packets with another container's source address.
    """
    nets = [ipaddress.ip_network(n) for n in [*PRIVATE_V4, *blocked_networks]]
    v4 = ipaddress.collapse_addresses(n for n in nets if n.version == 4)  # nft refuses overlaps
    return "\n".join([
        f"# {HEADER}",
        "table inet thinny",
        "delete table inet thinny",
        "table inet thinny {",
        f"\tset blocked_v4 {{ type ipv4_addr; flags interval; elements = {{ {', '.join(map(str, v4))} }}; }}",
        "\tchain forward {",
        "\t\ttype filter hook forward priority filter - 1; policy accept;",
        f'\t\tiifname "thinny-*" oifname != "{interface}" drop',
        '\t\tiifname "thinny-*" ip daddr @blocked_v4 drop',
        '\t\tiifname "thinny-*" meta nfproto ipv6 drop',
        '\t\toifname "thinny-*" ct state != { established, related } drop',
        "\t}",
        "\tchain input {",
        "\t\ttype filter hook input priority filter - 1; policy accept;",
        '\t\tiifname "thinny-*" ct state != { established, related } drop',
        "\t}",
        "\tchain postrouting {",
        "\t\ttype nat hook postrouting priority srcnat; policy accept;",
        f'\t\toifname "{interface}" ip saddr {SUBNET} masquerade',
        "\t}",
        "}",
        "",
    ])


def profile(s: Settings) -> str:
    """The Incus profile of every instance container, complete in itself (JSON is YAML)."""
    return json.dumps({
        "description": "thinny instance container",
        "config": {
            "boot.autostart": "true",
            "limits.cpu": str(s.container_cpu),
            "limits.memory": f"{s.container_memory_mb}MiB",
            "limits.processes": "2000",
            "security.idmap.isolated": "true",   # its own host uid range
            "security.nesting": "true",          # Docker inside
            "security.privileged": "false",
        },
        "devices": {
            "root": {"type": "disk", "path": "/", "pool": POOL, "size": f"{s.container_disk_gb}GiB"},
            "tun": {"type": "unix-char", "source": "/dev/net/tun", "path": "/dev/net/tun"},  # Tailscale inside
        },
    }, indent=1)


def network_file(address: str) -> str:
    """systemd-networkd inside a container: its routed address, no DHCP; public resolvers, since
    private ones (the tailnet's included) are out of reach."""
    return (f"# {HEADER}\n[Match]\nName=eth0\n\n[Network]\nAddress={address}/32\nDNS=1.1.1.1\nDNS=9.9.9.9\n\n"
            "[Route]\nGateway=169.254.0.1\nGatewayOnLink=yes\n")


# Instance containers only run behind their firewall: incusd does not start without the table, and
# restarting nftables (on Debian it flushes every table) restarts incusd, which reloads it.
# Restarting incusd leaves the containers running.
INCUS_DROPIN = f"""# {HEADER}
[Unit]
After=nftables.service
PartOf=nftables.service

[Service]
ExecStartPre=/usr/sbin/nft -f {FIREWALL_FILE}
"""

