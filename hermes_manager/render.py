from .settings import Settings

HEADER = "Generated by hermes-manager from /etc/hermes-manager/site.toml; do not edit by hand."
TAILNET = ("100.64.0.0/10", "fd7a:115c:a1e0::/48")
INSTALL = "/opt/hermes"
CHECKOUT = "/opt/hermes/hermes-agent"


def to_yaml(value, indent: int = 0) -> str:
    """Minimal YAML for nested dicts, lists and scalars (strings as JSON, which YAML accepts)."""
    pad = "  " * indent
    lines = []
    for key, item in value.items():
        if isinstance(item, dict) and item:
            lines.append(f"{pad}{key}:")
            lines.append(to_yaml(item, indent + 1))
        else:
            lines.append(f"{pad}{key}: {json.dumps(item)}")
    return "\n".join(lines)


def managed_config(s: Settings) -> str:
    plugins = ["model-guard"] + ([s.language_pack] if s.language_pack else [])
    config = {
        "model": {"provider": s.model_provider, "default": s.model},
        "agent": {"reasoning_effort": s.reasoning_effort},
        # Pinned lists replace the user's lists, so everything that must be on is listed here.
        "plugins": {"enabled": plugins, "disabled": []},
        "terminal": {
            "backend": "docker",
            "docker_image": s.sandbox_image,
            "docker_mount_cwd_to_workspace": False,
            "docker_volumes": [],
            "docker_forward_env": [],
            "docker_extra_args": [],
            "docker_shared_container_key": "",
            "container_cpu": s.sandbox_cpu,
            "container_memory": s.sandbox_memory_mb,
            "container_disk": s.sandbox_disk_mb,
            "container_persistent": True,
        },
        "bot_desktop": {"placement": "terminal"},
        "security": {"redact_secrets": True},
        "approvals": {"mode": s.approvals},
    }
    return f"# {HEADER}\n# Hermes managed scope: these values win over every person's own config.\n{to_yaml(config)}\n"


def managed_env() -> str:
    return (f"# {HEADER}\n# World-readable: never put secrets here.\n"
            "HERMES_DOCKER_BINARY=/usr/local/bin/hermes-podman\n"
            "TERMINAL_ENV=docker\n"
            "HERMES_CONFIG_BACKEND=file\n")


def allowed_models(s: Settings) -> str:
    return f"# {HEADER}\n# Models people may chat with, read by the model-guard plugin on every turn.\n" + \
        "".join(f"{m}\n" for m in s.allowed_models)


def model_guard_message(s: Settings) -> str:
    return s.model_guard_message + "\n"


def ui_preferences(s: Settings) -> dict[str, str]:
    """Webapp look for a new person (keys of Hermes's ui-preferences.json)."""
    def key(model):
        return f"{s.model_provider}::{model}"
    allowed = [key(m) for m in s.allowed_models]
    return {
        "hermes-desktop-mode-v1": s.theme,
        "hermes.desktop.chat-text-scale.v1": str(s.text_scale),
        "hermes.desktop.interfaceMode.v1": s.interface,
        "hermes.desktop.visible-models": json.dumps(allowed),
        "hermes.desktop.panesFlipped": "false",
        "hermes.desktop.showAllProfiles": "false",
        "hermes.desktop.model-presets": json.dumps(
            {key(s.model): {"effort": s.reasoning_effort, "serviceTier": "normal", "fast": False}}),
        # Models missing here show up as "new" in the model picker.
        "hermes.desktop.known-models": json.dumps(sorted(set(allowed) | {key(m) for m in s.known_models})),
    }


def host_for_url(address: str) -> str:
    return f"[{address}]" if ipaddress.ip_address(address).version == 6 else address


def person_url(s: Settings, name: str, access: str, port: int, *, url: str = "", tailscale_name: str = "") -> str:
    """The address a person opens; Hermes's webapp.public_url."""
    if access == "lan":
        return f"https://{host_for_url(s.lan_address)}:{port}/"
    if access == "tailscale":
        return f"https://{tailscale_name}:{port}/"
    if access == "local":
        return f"http://{name}.localhost:{port}/"
    return url


def caddyfile(s: Settings, lan_ports: list[int]) -> str:
    host = host_for_url(s.lan_address)
    sites = "".join(
        f"\nhttps://{host}:{port} {{\n\tbind {s.lan_address}\n\ttls internal\n\treverse_proxy 127.0.0.1:{port}\n}}\n"
        for port in lan_ports)
    # No admin API: on localhost it would let any account rewrite the proxy.
    return f"# {HEADER}\n{{\n\tadmin off\n\tskip_install_trust\n}}\n{sites}"


def firewall(*, people_uids: list[int], slice_uids: list[int], proxy_uids: list[int],
             blocked_networks: list[str], tailscale: bool) -> str:
    """nft table for person isolation.

    Loopback: a new TCP connection to a socket inside a person's user slice is accepted only
    from root, that person, or a proxy account (the sender's uid travels in the packet mark).
    nft resolves cgroup paths when loading, so only slices that exist get a rule; the table
    is reloaded whenever a person's user manager starts.
    Outgoing: people may not reach the blocked networks (the tailnet when Tailscale runs,
    except MagicDNS).
    """
    nets = [ipaddress.ip_network(n) for n in [*blocked_networks, *(TAILNET if tailscale else ())]]
    # nft refuses overlapping intervals in one set.
    v4 = list(ipaddress.collapse_addresses(n for n in nets if n.version == 4))
    v6 = list(ipaddress.collapse_addresses(n for n in nets if n.version == 6))

    def elements(items):
        return f" elements = {{ {', '.join(str(i) for i in items)} }};" if items else ""

    out = ['\t\toif "lo" meta l4proto tcp ct state new meta mark set meta skuid']
    if tailscale:
        out += ['\t\tmeta skuid @people ip daddr 100.100.100.100 meta l4proto { tcp, udp } th dport 53 accept',
                '\t\tmeta skuid @people ip6 daddr fd7a:115c:a1e0::53 meta l4proto { tcp, udp } th dport 53 accept']
    out += ['\t\tmeta skuid @people ip daddr @blocked_v4 reject',
            '\t\tmeta skuid @people ip6 daddr @blocked_v6 reject']
    inp = []
    for uid in sorted(set(people_uids) & set(slice_uids)):
        allowed = ", ".join(str(u) for u in sorted({0, uid, *proxy_uids}))
        inp.append(f'\t\tiif "lo" meta l4proto tcp ct state new socket cgroupv2 level 2 '
                   f'"user.slice/user-{uid}.slice" meta mark != {{ {allowed} }} reject with tcp reset')
    return "\n".join([
        f"# {HEADER}",
        "table inet hermes_manager",
        "delete table inet hermes_manager",
        "table inet hermes_manager {",
        f"\tset people {{ type uid;{elements(sorted(people_uids))} }}",
        f"\tset blocked_v4 {{ type ipv4_addr; flags interval;{elements(v4)} }}",
        f"\tset blocked_v6 {{ type ipv6_addr; flags interval;{elements(v6)} }}",
        "\tchain output {",
        "\t\ttype filter hook output priority filter; policy accept;",
        *out,
        "\t}",
        "\tchain input {",
        "\t\ttype filter hook input priority filter; policy accept;",
        *inp,
        "\t}",
        "}",
        "",
    ])


def launcher() -> str:
    return f"""#!/bin/sh
# {HEADER}
# The shared Hermes install. Root works on the install itself and must keep it traversable (711),
# or every person's hermes fails with "Permission denied".
if [ "$(id -u)" = 0 ] && [ -z "$HERMES_HOME" -o "$HERMES_HOME" = {INSTALL} ]; then
\texport HERMES_HOME={INSTALL} HERMES_HOME_MODE=0711
fi
exec {CHECKOUT}/.hermes/bin/hermes "$@"
"""


